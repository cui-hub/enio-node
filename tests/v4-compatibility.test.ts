import { readFile } from "node:fs/promises";
import { expect, it, vi } from "vitest";
import { createAgent, createMemoryCheckpointStore } from "../src/index.js";
import type { Checkpoint } from "../src/index.js";
import { answer, sequence } from "./helpers.js";

it("V4 resumes a checkpoint generated by the unchanged V3 tag without rewriting its binding or setup signature", async () => {
  const checkpoint = JSON.parse(
    await readFile(new URL("./fixtures/v3-checkpoint.json", import.meta.url), "utf8"),
  ) as Checkpoint;
  expect(checkpoint.delegation).toBeUndefined();
  expect(checkpoint.continuations).toBeUndefined();
  expect(checkpoint.setupSignature).toBeTypeOf("string");
  const store = createMemoryCheckpointStore();
  await store.save(checkpoint, new AbortController().signal);
  const execute = vi.fn(async () => ({ ok: true as const, content: "done" }));
  const result = await createAgent({
    model: sequence(answer("legacy resumed")),
    instructions: "V3 instructions",
    tools: [
      {
        name: "work",
        description: "work",
        effect: "read",
        parallelSafe: true,
        inputSchema: { type: "object" },
        execute,
      },
    ],
    toolExecution: { maxConcurrency: 2 },
    middlewares: [
      {
        name: "legacy-v3-trace",
        beforeAgent(setup) {
          return setup;
        },
      },
    ],
    checkpoints: { store, namespace: "legacy-v3" },
    hooks: {
      beforeTool(_call, ctx) {
        return ctx.resume?.data === true;
      },
    },
  }).resume({ checkpointId: checkpoint.id, data: true }, { context: {}, checkpointOwner: "owner" });
  expect(result.status).toBe("completed");
  expect(result.runId).toBe(checkpoint.runId);
  expect(result.finalText).toBe("legacy resumed");
  expect(result.historyComplete).toBe(true);
  expect(execute).toHaveBeenCalledOnce();
});
